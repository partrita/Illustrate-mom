//! Built-in **Molecule of the Month** color and outline presets.

use serde::{Deserialize, Serialize};

use crate::command::{AtomDescriptor, OutlineParams, WorldParams};

/// Signature rendering style presets inspired by David S. Goodsell's
/// *Molecule of the Month* and *JMolGraphics* (1992) illustrations.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PresetKind {
    /// Warm coral/pink/peach hemoglobin-style Goodsell palette + Heme emphasis.
    GoodsellClassic,
    /// Per-chain pastel palette assigning distinct soft hues to every chain.
    SubunitPastel,
    /// 1992 JMolGraphics black-and-white ink & soft conical shadow style.
    Monochrome1992,
    /// Soft CPK elemental colors (C, N, O, S, P, Fe/metals).
    CpkSoft,
}

impl PresetKind {
    /// Parses a preset identifier string (defaults to `GoodsellClassic` if unrecognized).
    #[must_use]
    pub fn from_id(id: &str) -> Self {
        match id {
            "subunit_pastel" => Self::SubunitPastel,
            "monochrome_1992" => Self::Monochrome1992,
            "cpk_soft" => Self::CpkSoft,
            _ => Self::GoodsellClassic,
        }
    }
}

/// Complete style bundle generated by a [`PresetKind`].
#[derive(Debug, Clone, PartialEq)]
pub struct StylePreset {
    pub descriptors: Vec<AtomDescriptor>,
    pub world: WorldParams,
    pub outline: OutlineParams,
}

fn rule(record: &str, pattern: &str, color: [f32; 3], radius: f32) -> AtomDescriptor {
    AtomDescriptor::from_strings(record, pattern, (0, 9999), color, radius)
        .expect("preset rule literals are always valid")
}

fn base_world(ixsize: i32, iysize: i32) -> WorldParams {
    WorldParams {
        rback: [1.0, 1.0, 1.0],
        rfog: [1.0, 1.0, 1.0],
        pfogh: 1.0,
        pfogl: 1.0,
        icone: 1,
        pcone: 0.0023,
        coneangle: 2.0,
        rcone: 1.0,
        pshadowmax: 0.2,
        ixsize,
        iysize,
    }
}

fn base_outline() -> OutlineParams {
    OutlineParams {
        enabled: true,
        l_low: 3.0,
        l_high: 10.0,
        ikernel: 4,
        l_diff_min: 0.0,
        l_diff_max: 5.0,
        r_low: 3.0,
        r_high: 10.0,
        g_low: 3.0,
        g_high: 8.0,
        resdiff: 6000.0,
    }
}

/// Builds descriptors, world settings, and outline parameters for `preset` given the
/// detected `chains` of a PDB structure.
#[must_use]
pub fn build_preset(preset: PresetKind, chains: &[char], canvas_pad: (i32, i32)) -> StylePreset {
    let mut descriptors = vec![
        rule("HETATM", "-----HOH--", [0.5, 0.5, 0.5], 0.0),
        rule("ATOM  ", "-H--------", [0.5, 0.5, 0.5], 0.0),
        rule("ATOM  ", "H---------", [0.5, 0.5, 0.5], 0.0),
    ];

    let mut world = base_world(canvas_pad.0, canvas_pad.1);
    let mut outline = base_outline();

    match preset {
        PresetKind::GoodsellClassic => {
            // Classic 2HHB-inspired pink/coral for chains A/C and peach/orange for others
            for &ch in chains {
                if ch == 'A' || ch == 'C' {
                    descriptors.push(rule(
                        "ATOM  ",
                        &format!("-C-------{ch}"),
                        [1.0, 0.6, 0.6],
                        1.6,
                    ));
                    descriptors.push(rule(
                        "ATOM  ",
                        &format!("-S-------{ch}"),
                        [1.0, 0.5, 0.5],
                        1.8,
                    ));
                    descriptors.push(rule(
                        "ATOM  ",
                        &format!("---------{ch}"),
                        [1.0, 0.5, 0.5],
                        1.5,
                    ));
                }
            }
            descriptors.push(rule("ATOM  ", "-C--------", [1.0, 0.8, 0.6], 1.6));
            descriptors.push(rule("ATOM  ", "-S--------", [1.0, 0.7, 0.5], 1.8));
            descriptors.push(rule("ATOM  ", "----------", [1.0, 0.7, 0.5], 1.5));
            descriptors.push(rule("HETATM", "FE---HEM--", [1.0, 0.8, 0.0], 1.8));
            descriptors.push(rule("HETATM", "-C---HEM--", [1.0, 0.3, 0.3], 1.6));
            descriptors.push(rule("HETATM", "-----HEM--", [1.0, 0.1, 0.1], 1.5));
            descriptors.push(rule("HETATM", "----------", [0.9, 0.6, 0.3], 1.5));
        }
        PresetKind::SubunitPastel => {
            const PALETTE: [[f32; 3]; 8] = [
                [0.98, 0.62, 0.62], // Rose
                [0.62, 0.80, 0.98], // Sky
                [0.65, 0.88, 0.68], // Sage
                [0.98, 0.80, 0.55], // Amber
                [0.80, 0.68, 0.96], // Lavender
                [0.58, 0.88, 0.85], // Teal
                [0.96, 0.68, 0.82], // Orchid
                [0.88, 0.85, 0.62], // Sand
            ];
            for (idx, &ch) in chains.iter().enumerate() {
                let base = PALETTE[idx % PALETTE.len()];
                let carbon = [
                    (base[0] + 0.12).min(1.0),
                    (base[1] + 0.12).min(1.0),
                    (base[2] + 0.12).min(1.0),
                ];
                descriptors.push(rule("ATOM  ", &format!("-C-------{ch}"), carbon, 1.6));
                descriptors.push(rule("ATOM  ", &format!("-S-------{ch}"), base, 1.8));
                descriptors.push(rule("ATOM  ", &format!("---------{ch}"), base, 1.5));
            }
            descriptors.push(rule("ATOM  ", "-C--------", [0.88, 0.86, 0.82], 1.6));
            descriptors.push(rule("ATOM  ", "----------", [0.78, 0.76, 0.72], 1.5));
            descriptors.push(rule("HETATM", "FE---HEM--", [1.0, 0.82, 0.10], 1.8));
            descriptors.push(rule("HETATM", "----------", [0.95, 0.45, 0.35], 1.5));
        }
        PresetKind::Monochrome1992 => {
            descriptors.push(rule("ATOM  ", "-C--------", [0.96, 0.96, 0.96], 1.6));
            descriptors.push(rule("ATOM  ", "-S--------", [0.88, 0.88, 0.88], 1.8));
            descriptors.push(rule("ATOM  ", "----------", [0.92, 0.92, 0.92], 1.5));
            descriptors.push(rule("HETATM", "----------", [0.72, 0.72, 0.72], 1.5));
            world.pcone = 0.0040;
            world.coneangle = 1.6;
            world.pshadowmax = 0.35;
            outline.l_low = 2.5;
            outline.l_high = 8.5;
        }
        PresetKind::CpkSoft => {
            descriptors.push(rule("ATOM  ", "-C--------", [0.78, 0.80, 0.83], 1.6));
            descriptors.push(rule("ATOM  ", "-N--------", [0.46, 0.64, 0.94], 1.5));
            descriptors.push(rule("ATOM  ", "-O--------", [0.95, 0.44, 0.44], 1.5));
            descriptors.push(rule("ATOM  ", "-S--------", [0.96, 0.83, 0.34], 1.8));
            descriptors.push(rule("ATOM  ", "-P--------", [0.96, 0.62, 0.28], 1.8));
            descriptors.push(rule("ATOM  ", "----------", [0.74, 0.76, 0.80], 1.5));
            descriptors.push(rule("HETATM", "FE--------", [0.98, 0.74, 0.16], 1.8));
            descriptors.push(rule("HETATM", "-C--------", [0.68, 0.70, 0.74], 1.6));
            descriptors.push(rule("HETATM", "-N--------", [0.46, 0.64, 0.94], 1.5));
            descriptors.push(rule("HETATM", "-O--------", [0.95, 0.44, 0.44], 1.5));
            descriptors.push(rule("HETATM", "----------", [0.86, 0.60, 0.32], 1.5));
        }
    }

    StylePreset {
        descriptors,
        world,
        outline,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_presets_include_water_and_hydrogen_omissions() {
        let chains = ['A', 'B', 'C', 'D'];
        for preset in [
            PresetKind::GoodsellClassic,
            PresetKind::SubunitPastel,
            PresetKind::Monochrome1992,
            PresetKind::CpkSoft,
        ] {
            let built = build_preset(preset, &chains, (-30, -30));
            assert!(built.descriptors.len() >= 6);
            assert_eq!(built.descriptors[0].radius, 0.0);
            assert_eq!(built.descriptors[1].radius, 0.0);
        }
    }
}
